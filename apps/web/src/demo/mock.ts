// ---------------------------------------------------------------- recorded reads

const byPath = new Map<string, string[]>();
for (const k of Object.keys(data.fixtures)) {
  const [role, rest] = [k.slice(0, k.indexOf('|')), k.slice(k.indexOf('|') + 1)];
  const path = rest.split('?')[0]!;
  const list = byPath.get(`${role}|${path}`) ?? [];
  list.push(k);
  byPath.set(`${role}|${path}`, list);
}

/** Recorded answer for a GET: this role, then a visitor's view, exact query first, then any query. */
function recorded(pathAndQuery: string): Rec | null {
  const roles: Role[] = state.role === 'anon' ? ['anon'] : [state.role, 'anon'];
  const personal = /^\/api\/(auth|me|orders)\//.test(pathAndQuery) || /\/api\/store\/[^/]+\/(orders|reorder)/.test(pathAndQuery);
  const tryRoles = personal ? [state.role] : roles;
  for (const r of tryRoles) { const hit = data.fixtures[`${r}|${pathAndQuery}`]; if (hit) return clone(hit); }
  const path = pathAndQuery.split('?')[0]!;
  for (const r of tryRoles) { const keys = byPath.get(`${r}|${path}`); if (keys?.length) return clone(data.fixtures[keys[0]!]!); }
  return null;
}

// ---------------------------------------------------------------- helpers

const uuid = () => (crypto.randomUUID ? crypto.randomUUID() : `${Date.now().toString(16)}-${Math.random().toString(16).slice(2)}`);
const phoneOf = (p: unknown) => `+234${String(p ?? '').replace(/\D/g, '').slice(-10)}`;
const priceRole = (): 'anon' | 'buyer' => (state.role === 'buyer' ? 'buyer' : 'anon');

const productOf = (variantId: string): string | null =>
  Object.values(data.products).find((p: any) => p.variants?.some((v: any) => v.id === variantId))?.product?.id ?? null;

const baseUnit = (variantId: string): string | undefined =>
  Object.values(data.products).find((p: any) => p.variants?.some((v: any) => v.id === variantId))?.units?.find((u: any) => u.is_base)?.unit_id;

function unitPlural(variantId: string, unitId: string, qty: number, fallback: string): string {
  if (qty === 1) return fallback;
  for (const p of Object.values(data.products)) {
    if (!p.variants?.some((v: any) => v.id === variantId)) continue;
    return p.units?.find((x: any) => x.unit_id === unitId)?.plural ?? fallback;
  }
  return fallback;
}

function quote(items: { variant_id: string; unit_id?: string; qty: number }[]) {
  const table = data.prices[priceRole()];
  const lines = items.flatMap((it) => {
    const one = table[`${it.variant_id}|${it.unit_id ?? baseUnit(it.variant_id)}`];
    if (!one) return [];
    const factor = one.base_qty || 1;
    return [{ ...one, qty: it.qty, base_qty: factor * it.qty, unit_name: unitPlural(it.variant_id, one.unit_id, it.qty, one.unit_name), line_total_kobo: one.unit_price_kobo * factor * it.qty }];
  });
  return { lines, subtotal_kobo: lines.reduce((s, l) => s + l.line_total_kobo, 0), dropped: items.length - lines.length };
}

function storeProducts(slug: string, sp: URLSearchParams) {
  const q = (sp.get('q') ?? '').trim().toLowerCase();
  const cat = sp.get('category') ?? '';
  const limit = Number(sp.get('limit') ?? 24) || 24;
  const from = Number(sp.get('cursor') ?? 0) || 0;
  const all = data.lists.all.filter((p) => (!cat || p.category === cat) && (!q || `${p.name} ${p.category ?? ''}`.toLowerCase().includes(q)));
  const items = all.slice(from, from + limit);
  void slug;
  return { items, nextCursor: from + limit < all.length ? String(from + limit) : null };
}

/** Patch the shop's look (after a design is published in this tab). */
function withLook(body: any): any {
  if (!body || typeof body !== 'object') return body;
  if (state.design && 'design' in body && body.business) body.design = clone(state.design);
  if (state.design && 'storefront' in body) body.storefront = clone(state.design);
  const biz = body.business;
  if (biz && typeof biz === 'object') {
    if (state.brand) biz.brand_colour = state.brand;
    if (state.logo) biz.logo_url = state.logo;
    if (state.design && 'storefront' in biz) biz.storefront = clone(state.design);
  }
  return body;
}

// ---------------------------------------------------------------- orders made in the demo

function newOrder(input: any) {
  const q = quote((input.items ?? []) as any[]);
  if (!q.lines.length) return null;
  const view = clone(data.order.pending);
  const id = uuid();
  const o = view.order;
  const now = new Date();
  state.nextNumber = state.nextNumber ? state.nextNumber + 1 : (Number(o.order_number) || 100);
  const fee = input.delivery_method === 'delivery' ? 250_000 : 0;
  Object.assign(o, {
    id,
    order_number: state.nextNumber,
    created_at: now.toISOString(),
    updated_at: now.toISOString(),
    channel: input.channel === 'instagram' ? 'instagram' : 'web',
    delivery_method: input.delivery_method ?? o.delivery_method,
    delivery_address: input.delivery_address ?? null,
    note: input.note ?? null,
    subtotal_kobo: q.subtotal_kobo,
    delivery_fee_kobo: fee,
    total_kobo: q.subtotal_kobo + fee,
    amount_paid_kobo: 0,
    balance_kobo: q.subtotal_kobo + fee,
  });
  o.reservation_expires_at = new Date(now.getTime() + 45 * 60_000).toISOString();
  o.tracking_token = uuid().replace(/-/g, '').slice(0, 22);
  if (view.delivery) { view.delivery.delivery_method = o.delivery_method; view.delivery.fulfilment_status = 'unfulfilled'; }
  const template = o.items?.[0] ?? {};
  o.items = q.lines.map((l) => ({
    ...template,
    id: uuid(), order_id: id, created_at: now.toISOString(),
    variant_id: l.variant_id, unit_id: l.unit_id, product_id: productOf(l.variant_id), name: l.name, variant_label: l.variant_label,
    unit_qty: l.qty, base_qty: l.base_qty, price_source: l.price_source,
    unit_price_kobo: l.unit_price_kobo, line_total_kobo: l.line_total_kobo,
  }));
  view.payments = [];
  state.orders[id] = view;
  save();
  return view;
}

function markPaid(id: string) {
  const view = state.orders[id];
  if (!view) return false;
  const paid = data.order.paid?.order ?? {};
  const o = view.order;
  for (const k of ['status', 'payment_status', 'fulfilment_status']) if (k in paid) o[k] = paid[k];
  o.amount_paid_kobo = o.total_kobo;
  o.balance_kobo = 0;
  o.reservation_expires_at = null;
  o.confirmed_at = o.updated_at = new Date().toISOString();
  if (view.delivery) view.delivery.fulfilment_status = o.fulfilment_status;
  view.payments = [{ method: 'virtual_account', amount_kobo: o.total_kobo, received_at: new Date().toISOString() }];
  save();
  return true;
}

function myOrdersList(body: any): any {
  const mine = Object.values(state.orders).filter(Boolean).reverse();
  if (!mine.length || !Array.isArray(body?.orders)) return body;
  const shape = body.orders[0] ?? {};
  const rows = mine.map((v: any) => {
    const o = v.order;
    const row: any = { ...shape };
    for (const k of Object.keys(shape)) if (k in o) row[k] = o[k];
    return row;
  });
  return { ...body, orders: [...rows, ...body.orders] };
}

