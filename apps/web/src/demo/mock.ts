/** Reports: answer with the recorded range of the same length (the demo may be opened on a later day). */
function reportFor(req: Req): Rec | null {
  const span = (sp: URLSearchParams) => {
    const f = sp.get('from'), t = sp.get('to');
    return f && t ? Math.round((Date.parse(t) - Date.parse(f)) / 864e5) : -1;
  };
  const want = span(req.search);
  const channel = req.search.get('channel') ?? '';
  const keys = byPath.get(`owner|${req.path}`) ?? [];
  let best: string | null = null, bestScore = Infinity;
  for (const k of keys) {
    const sp = new URLSearchParams(k.split('?')[1] ?? '');
    const score = Math.abs(span(sp) - want) + ((sp.get('channel') ?? '') === channel ? 0 : 1000);
    if (score < bestScore) { best = k; bestScore = score; }
  }
  return best ? clone(data.fixtures[best]!) : null;
}

/** Orders made in this tab, as rows of the dashboard's order list. */
function ownerRows(shape: any): any[] {
  return Object.values(state.orders).reverse().map((v: any) => {
    const o = v.order;
    const row: any = { ...shape };
    for (const k of Object.keys(shape)) if (k in o) row[k] = o[k];
    return { ...row, customer: 'Chidi Okafor', customer_phone: '+2348090000001', lines: o.items.length, needs_attention: null };
  });
}

function ownerOrders(req: Req): Rec | null {
  const keys = byPath.get(`owner|${req.path}`) ?? [];
  const plain = keys.find((k) => !k.includes('?') || k.endsWith('?'));
  const rec = plain ? clone(data.fixtures[plain]!) : null;
  if (!rec?.body?.orders) return rec;
  const sp = req.search;
  const q = (sp.get('q') ?? '').trim().toLowerCase();
  let orders: any[] = [...ownerRows(rec.body.orders[0] ?? {}), ...rec.body.orders];
  for (const f of ['channel', 'status', 'payment_status', 'fulfilment_status']) {
    const v = sp.get(f);
    if (v) orders = orders.filter((o) => o[f] === v);
  }
  if (q) orders = orders.filter((o) => `${o.order_number} ${o.customer ?? ''} ${o.customer_phone ?? ''}`.toLowerCase().includes(q));
  return ok({ ...rec.body, orders });
}

/** Dashboard view of an order placed in this tab, built on a recorded order's layout. */
function ownerOrder(id: string): Rec | null {
  const v = state.orders[id];
  if (!v) return null;
  const tk = Object.keys(data.fixtures).find((k) => /^owner\|\/api\/biz\/[^/]+\/orders\/[0-9a-f-]{36}$/.test(k));
  const t = tk ? clone(data.fixtures[tk]!.body) : {};
  const body: any = { ...t, order: { ...(t.order ?? {}), ...v.order, customer_name: 'Chidi Okafor' }, payments: v.payments };
  if ('items' in t) body.items = v.order.items;
  if ('delivery' in t) body.delivery = v.delivery ?? null;
  return ok(body);
}

async function handle(req: Req): Promise<Rec> {
  for (const [method, re, fn] of routes) {
    if (method !== req.method) continue;
    const m = req.path.match(re);
    if (!m) continue;
    const res = await fn(req, m);
    if (res) return res;
  }
  if (req.method === 'GET' && state.role === 'owner') {
    if (/^\/api\/biz\/[^/]+\/reports\//.test(req.path)) { const r = reportFor(req); if (r) return r; }
    if (/^\/api\/biz\/[^/]+\/orders$/.test(req.path)) { const r = ownerOrders(req); if (r) return r; }
    const m = req.path.match(/^\/api\/biz\/[^/]+\/orders\/([0-9a-f-]{36})$/);
    if (m) { const r = ownerOrder(m[1]!); if (r) return r; }
  }
  if (req.method === 'GET') {
    const rec = recorded(req.full);
    if (rec) return { ...rec, body: withLook(rec.body) };
    return fail(404, 'not_found');
  }
  notSaved();
  return ok({ ok: true, id: uuid() });
}

// ---------------------------------------------------------------- install

export function resetDemo(): void {
  state = fresh();
  try { sessionStorage.removeItem(KEY); for (const k of Object.keys(localStorage)) if (k.startsWith('trawer')) localStorage.removeItem(k); } catch { /* storage off */ }
  window.location.hash = '/';
  window.location.reload();
}

export function install(): void {
  const realFetch = window.fetch.bind(window);
  window.fetch = async (input: RequestInfo | URL, init?: RequestInit) => {
    const url = new URL(typeof input === 'string' || input instanceof URL ? String(input) : input.url, window.location.href);
    if (!url.pathname.startsWith('/api/')) return realFetch(input, init);
    const body = init?.body;
    const req: Req = {
      method: (init?.method ?? 'GET').toUpperCase(),
      path: url.pathname,
      search: url.searchParams,
      full: `${url.pathname}${url.search}`,
      json: typeof body === 'string' ? (() => { try { return JSON.parse(body); } catch { return null; } })() : null,
      form: body instanceof FormData ? body : null,
    };
    await new Promise((r) => setTimeout(r, req.method === 'GET' ? 60 + Math.random() * 120 : 250));
    if (init?.signal?.aborted) throw new DOMException('Aborted', 'AbortError');
    const res = await handle(req);
    return new Response(JSON.stringify(res.body), { status: res.status, headers: { 'content-type': 'application/json' } });
  };

  // No live connection to a server: order pages fall back to polling (answered above).
  (window as any).EventSource = undefined;

  // Plain links point at app paths; in the demo those live after the `#`.
  document.addEventListener('click', (e) => {
    if (e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey) return;
    const a = (e.target as Element | null)?.closest?.('a[href]');
    const href = a?.getAttribute('href');
    if (!href || !href.startsWith('/') || href.startsWith('//')) return;
    e.preventDefault();
    if (href.startsWith('/api/') || href.startsWith('/media/')) { toast('Downloads (PDF, CSV, your data) are off in the demo'); return; }
    window.location.hash = href;
  }, true);

  if (!window.location.hash || window.location.hash === '#' || window.location.hash === '#/') window.location.hash = '/s/balogun';
}
