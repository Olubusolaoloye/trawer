/**
 * In-browser stand-in for the Trawer API, used only by the demo build (VITE_DEMO=1).
 *
 * Reads are answered from responses recorded from the real API against the seeded sample shop
 * (scripts/record-demo.cjs → src/demo/data.json). The flows people try first are live: signing in,
 * search and category filters, cart prices, checkout → bank transfer → paid, and publishing a
 * store design. Every other change is acknowledged but not kept. State lives in this tab only.
 */
/* eslint-disable @typescript-eslint/no-explicit-any */
