import { describe, expect, it } from 'vitest';
import { ean13Bars, ean13CheckDigit, ean13Modules, ean13Text, isValidEan13 } from '../src/barcode';

describe('EAN-13', () => {
  it('check digits match published examples', () => {
    expect(ean13CheckDigit('400638133393')).toBe(1); // 4006381333931
    expect(ean13CheckDigit('978030640615')).toBe(7); // ISBN 978-0-306-40615-7
    expect(isValidEan13('4006381333931')).toBe(true);
    expect(isValidEan13('4006381333932')).toBe(false);
  });

  it('encodes guards, parity and digits (reference pattern for 4006381333931)', () => {
    const m = ean13Modules('4006381333931');
    expect(m).toHaveLength(95);
    expect(m.slice(0, 3)).toBe('101');
    expect(m.slice(45, 50)).toBe('01010');
    expect(m.slice(92)).toBe('101');
    // first digit 4 → parity LGLLGG; digit "0" in L = 0001101, digit "0" in G = 0100111
    expect(m.slice(3, 10)).toBe('0001101');
    expect(m.slice(10, 17)).toBe('0100111');
    // right side digit "1" in R = 1100110 (last digit, before the end guard)
    expect(m.slice(85, 92)).toBe('1100110');
  });

  it('bars cover every dark module exactly once', () => {
    const code = '2000000000015'; // generated by the database (app.ean13)
    expect(isValidEan13(code)).toBe(true);
    const modules = ean13Modules(code);
    const dark = ean13Bars(code).reduce((n, [, w]) => n + w, 0);
    expect(dark).toBe([...modules].filter((c) => c === '1').length);
    expect(ean13Text(code)).toBe('2 000000 000015');
  });

  it('rejects anything that is not a valid code', () => {
    expect(() => ean13Modules('123')).toThrow();
    expect(() => ean13Modules('2000000000174')).toThrow();
  });
});
